#!/usr/bin/env bash
set -euo pipefail

export PLAYWRIGHT_BROWSERS_PATH=0
SCRIPT_DIR="/usr/src/microsoft-rewards-script"
cd "$SCRIPT_DIR"

: "${TZ:=UTC}"
export TZ
ln -snf "/usr/share/zoneinfo/$TZ" /etc/localtime
printf '%s\n' "$TZ" > /etc/timezone
dpkg-reconfigure -f noninteractive tzdata

SCHEDULE_OVERRIDE="${SCHEDULE_FILE:-$SCRIPT_DIR/config/schedule.json}"
if [ "${API_MODE:-false}" != "true" ]; then
  if [ -z "${CRON_SCHEDULE:-}" ] && [ ! -f "$SCHEDULE_OVERRIDE" ]; then
    echo "ERROR: Set CRON_SCHEDULE or provide config/schedule.json for scheduler mode." >&2
    echo "       To configure accounts and scheduling later, set API_MODE=true." >&2
    exit 1
  fi

  # Credential files are application data. Never source or evaluate them here.
  has_account=false
  while IFS= read -r name; do
    if [[ "$name" =~ ^ACCOUNT_[1-9][0-9]*_EMAIL$ ]] && [ -n "${!name:-}" ]; then
      has_account=true
      break
    fi
  done < <(compgen -e)
  if [ "$has_account" = false ] && [ ! -f "$SCRIPT_DIR/config/accounts.env" ]; then
    echo "ERROR: Scheduler mode requires ACCOUNT_N_EMAIL or config/accounts.env." >&2
    exit 1
  fi
fi

CONFIG_FILE="$SCRIPT_DIR/config/config.json"
CONFIG_EXAMPLE="$SCRIPT_DIR/config.example.json"
if [ ! -f "$CONFIG_EXAMPLE" ]; then
  echo "ERROR: config.example.json not found at $CONFIG_EXAMPLE - image may be corrupt." >&2
  exit 1
fi
if [ -d "$CONFIG_FILE" ]; then
  echo "ERROR: $CONFIG_FILE is a directory, not a file." >&2
  exit 1
fi

SYNC_ARGS=(--config "$CONFIG_FILE" --example "$CONFIG_EXAMPLE")
if [ "${CONFIG_AUTO_SYNC:-false}" = "true" ]; then
  SYNC_ARGS+=(--patch)
fi
node "$SCRIPT_DIR/dist/util/ConfigSync.js" sync "${SYNC_ARGS[@]}"
node "$SCRIPT_DIR/dist/util/ConfigEnvOverrides.js" apply --config "$CONFIG_FILE"
ln -sf "$CONFIG_FILE" "$SCRIPT_DIR/config.json"
echo "[entrypoint] Config ready."

: "${API_HOST:=0.0.0.0}"
export API_HOST

# This root-owned snapshot is generated by Bash, never from account-file text.
# Cron restores the original environment; the app parses accounts.env as data.
(umask 077; export -p > /etc/container_env)
chmod 600 /etc/container_env

# Use the shared schedule validator for both modes. With no schedule it removes
# stale jobs; cron still runs so a later dashboard update takes effect immediately.
node scripts/api/apply-schedule.js

start_initial_run() {
  if [ "${RUN_ON_START:-false}" = "true" ]; then
    echo "[entrypoint] Starting initial run at $(date)"
    SKIP_RANDOM_SLEEP=true scripts/docker/run_daily.sh &
    initial_pid=$!
  fi
}

if [ "${API_MODE:-false}" != "true" ]; then
  start_initial_run
  echo "[entrypoint] Starting scheduler (TZ: $TZ)"
  exec cron -f
fi

cron_pid=''
api_pid=''
initial_pid=''
cleanup() {
  trap - EXIT INT TERM
  for pid in "$initial_pid" "$api_pid" "$cron_pid"; do
    [ -z "$pid" ] || kill -TERM "$pid" 2>/dev/null || true
  done
  for pid in "$initial_pid" "$api_pid" "$cron_pid"; do
    [ -z "$pid" ] || wait "$pid" 2>/dev/null || true
  done
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

cron -f &
cron_pid=$!
echo "[entrypoint] Cron started (TZ: $TZ); scheduling can be changed from the dashboard."
node scripts/api/server.js &
api_pid=$!
echo "[entrypoint] Control API started on ${API_HOST}:${API_PORT:-3010}"
start_initial_run

# Treat either service exiting as a container failure, including clean exits.
status=0
wait -n "$cron_pid" "$api_pid" || status=$?
echo "[entrypoint] ERROR: API or cron exited; stopping container." >&2
[ "$status" -ne 0 ] || status=1
exit "$status"
